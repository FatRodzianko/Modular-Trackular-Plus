"""Builds the Synth FX default pack (synthfx-sdk/pack/) into .ptsfx files, and with --embed
writes core/mods/synthfx/synthfxPack.inc, the firmware's copy (written to /SynthFX/ on the
card when a file is missing).

    python tools/synthfx/build_pack.py [--toolchain PREFIX] [--out DIR] [--embed] [--check]

--check builds the pack and fails if the firmware's copy differs from it (a release-tier job).
Runs where the Arm toolchain is (WSL here).
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SDK = ROOT / "synthfx-sdk"
sys.path.insert(0, str(SDK))
import ptsfx_builder  # noqa: E402

# (file on the card, source): the pack, in the order the slot's list shows them
PACK = [
    ("Overdrive.ptsfx", "overdrive.cpp"),
    ("Distortion.ptsfx", "distortion.cpp"),
    ("BitCrusher.ptsfx", "bitcrusher.cpp"),
    ("Chorus.ptsfx", "chorus.cpp"),
    ("Flanger.ptsfx", "flanger.cpp"),
    ("Phaser.ptsfx", "phaser.cpp"),
]
INC = ROOT / "core" / "mods" / "synthfx" / "synthfxPack.inc"


def build(out: Path, tool: str) -> dict[str, bytes]:
    files = {}
    for name, src in PACK:
        dst = out / name
        ptsfx_builder.build([SDK / "pack" / src], dst, tool, [str(SDK / "pack"), str(ROOT / "core" / "mods" / "synthfx")],
                            [], quiet=False)
        files[name] = dst.read_bytes()
    return files


def embed_text(files: dict[str, bytes]) -> str:
    lines = ["// Modular-Trackular mods. SPDX-License-Identifier: MIT",
             "//",
             "// Generated by tools/synthfx/build_pack.py --embed from synthfx-sdk/pack/: the Synth FX",
             "// default pack, written to /SynthFX/ when a file is missing (synthfxPlugins.cpp). Don't",
             "// edit; rebuild it. The release tier checks it matches the sources (--check).",
             ""]
    for i, (name, data) in enumerate(files.items()):
        lines.append(f"alignas(4) static const uint8_t kPack{i}[{len(data)}] = {{")
        for o in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[o:o + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const PackFile kPack[] = {")
    for i, (name, data) in enumerate(files.items()):
        lines.append(f'    {{ "{name}", kPack{i}, sizeof(kPack{i}) }},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--toolchain", default="arm-none-eabi-")
    ap.add_argument("--out", type=Path, default=ROOT / "build" / "synthfx" / "pack")
    ap.add_argument("--embed", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        if a.check:
            with tempfile.TemporaryDirectory() as tmp:
                text = embed_text(build(Path(tmp), a.toolchain))
            same = INC.exists() and INC.read_text(encoding="utf-8") == text
            print("the firmware's pack matches its sources" if same else
                  "FAIL the firmware's pack (synthfxPack.inc) differs from synthfx-sdk/pack: rebuild it with --embed")
            return 0 if same else 1
        files = build(a.out, a.toolchain)
        if a.embed:
            INC.write_text(embed_text(files), encoding="utf-8", newline="\n")
            print(f"wrote {INC.relative_to(ROOT)}: {sum(len(d) for d in files.values())} bytes in {len(files)} files")
    except ptsfx_builder.BuildError as e:
        print(f"FAIL {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
