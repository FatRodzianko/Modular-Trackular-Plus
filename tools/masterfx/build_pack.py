"""Builds the Master FX default pack (masterfx-sdk/pack/) into .ptmfx files, and with --embed
writes core/mods/masterfx/masterfxPack.inc, the firmware's copy (written to /MasterFX/ on the
card when a file is missing).

    python tools/masterfx/build_pack.py [--toolchain PREFIX] [--out DIR] [--embed] [--check]

--check builds the pack and fails if the firmware's copy differs from it (a release-tier job).
Runs where the Arm toolchain is (WSL here).
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SDK = ROOT / "masterfx-sdk"
sys.path.insert(0, str(SDK))
import ptmfx_builder  # noqa: E402

# (file on the card, source, defines): the pack, in the order the slots' lists show them. The
# reverbs and delays are in the order of masterfx-1.x's lists, so a version 1 project's index
# maps to its file (masterfx.cpp).
PACK = [
    ("Freeverb.ptmfx", "pack.cpp", ["FX_FREEVERB"]),
    ("Plate.ptmfx", "pack.cpp", ["FX_PLATE"]),
    ("Spring.ptmfx", "pack.cpp", ["FX_SPRING"]),
    ("Shimmer.ptmfx", "pack.cpp", ["FX_SHIMMER"]),
    ("Gated.ptmfx", "pack.cpp", ["FX_GATED"]),
    ("Reverse.ptmfx", "pack.cpp", ["FX_REVERSE"]),
    ("Tape.ptmfx", "pack.cpp", ["FX_TAPE"]),
    ("BBD.ptmfx", "pack.cpp", ["FX_BBD"]),
    ("Glue.ptmfx", "glue.cpp", []),
]
INC = ROOT / "core" / "mods" / "masterfx" / "masterfxPack.inc"


def build(out: Path, tool: str) -> dict[str, bytes]:
    files = {}
    for name, src, defines in PACK:
        dst = out / name
        ptmfx_builder.build([SDK / "pack" / src], dst, tool, [str(SDK / "pack")], defines, quiet=False)
        files[name] = dst.read_bytes()
    return files


def embed_text(files: dict[str, bytes]) -> str:
    lines = ["// Modular-Trackular mods. SPDX-License-Identifier: MIT",
             "//",
             "// Generated by tools/masterfx/build_pack.py --embed from masterfx-sdk/pack/: the Master FX",
             "// default pack, written to /MasterFX/ when a file is missing (masterfxPlugins.cpp). Don't",
             "// edit; rebuild it. The release tier checks it matches the sources (--check).",
             ""]
    for i, (name, data) in enumerate(files.items()):
        lines.append(f"alignas(4) static const uint8_t kPack{i}[{len(data)}] = {{")
        for o in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[o:o + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const PackFile kPack[] = {")
    for i, (name, data) in enumerate(files.items()):
        lines.append(f'    {{ "{name}", kPack{i}, sizeof(kPack{i}) }},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--toolchain", default="arm-none-eabi-")
    ap.add_argument("--out", type=Path, default=ROOT / "build" / "masterfx" / "pack")
    ap.add_argument("--embed", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        if a.check:
            with tempfile.TemporaryDirectory() as tmp:
                text = embed_text(build(Path(tmp), a.toolchain))
            same = INC.exists() and INC.read_text(encoding="utf-8") == text
            print("the firmware's pack matches its sources" if same else
                  "FAIL the firmware's pack (masterfxPack.inc) differs from masterfx-sdk/pack: rebuild it with --embed")
            return 0 if same else 1
        files = build(a.out, a.toolchain)
        if a.embed:
            INC.write_text(embed_text(files), encoding="utf-8", newline="\n")
            print(f"wrote {INC.relative_to(ROOT)}: {sum(len(d) for d in files.values())} bytes in {len(files)} files")
    except ptmfx_builder.BuildError as e:
        print(f"FAIL {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
